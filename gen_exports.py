# -*- coding: utf-8 -*-
"""gen_exports.py —— 用原厂库的 .dynsym 生成链接器 version script（导出白名单）

背景
----
重建库是"按源码重新编译"的产物，它会把源码里出现的所有外部可见符号都导出，
包括：
  · 原库根本没有的 Qt2 模板实例（QMap/QCache/QMapIterator<QString,...> 等）
  · 我们自己的调试设施（amLogWrite / ring_dump_file / crash_install / g_ring …）
实测多出 109 个。这些多余导出在动态链接器眼里是**合法的符号提供者**：
其它固件库（mystuff、SoftManage、各种 app）如果有同名 UND，就可能绑到
我们的实现上而不是它原本的提供者，属于典型的"符号抢占"隐患。

做法
----
以 orig_local.so 的**已定义** .dynsym 条目（st_shndx != 0）为白名单，
生成 exports.map：
    { global: <原库全部导出>; local: *; };
链接时 -Wl,--version-script 生效后，本库的 .dynsym 与原库逐名一致。

注意
----
1. 匿名版本节点（不写版本名）只改可见性、**不引入符号版本**，所以导出名
   仍是 `foo` 而不是 `foo@@V1`，与原库一致（原库无版本节）。
2. `local: *;` 会让内部符号变 hidden，因此**必须**先确认白名单覆盖原库
   全部导出，否则某个库会因解析失败而加载不了。verify_exports.py 复查。
3. 用法：python gen_exports.py [orig.so] [out.map]
"""
import struct
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def dynsym_defined(path):
    """返回 {name: (value, size, shndx, info)}，含定义与未定义两类。"""
    d = open(path, 'rb').read()
    e_shoff = struct.unpack_from('<I', d, 0x20)[0]
    e_shentsize = struct.unpack_from('<H', d, 0x2E)[0]
    e_shnum = struct.unpack_from('<H', d, 0x30)[0]
    e_shstrndx = struct.unpack_from('<H', d, 0x32)[0]
    secs = [struct.unpack_from('<IIIIIIIIII', d, e_shoff + i * e_shentsize)
            for i in range(e_shnum)]
    shstr = secs[e_shstrndx]
    shstrb = d[shstr[4]:shstr[4] + shstr[5]]

    def secname(off):
        end = shstrb.find(b'\0', off)
        return shstrb[off:end].decode('latin1')

    byname = {}
    for s in secs:
        byname.setdefault(secname(s[0]), s)      # 同名节取第一个（.dynsym 唯一）
    ds = byname['.dynsym']
    st = byname['.dynstr']
    strb = d[st[4]:st[4] + st[5]]

    out = {}
    for i in range(ds[5] // ds[9]):
        o = ds[4] + i * ds[9]
        name, val, size, info, other, shndx = struct.unpack_from('<IIIBBH', d, o)
        if not name:
            continue
        end = strb.find(b'\0', name)
        s = strb[name:end].decode('latin1')
        if s:
            out[s] = (val, size, shndx, info)
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'orig_local.so')
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, 'exports.map')
    syms = dynsym_defined(src)
    names = sorted(k for k, v in syms.items() if v[2] != 0)

    with open(dst, 'w', newline='\n') as f:
        f.write('/* AUTO-GENERATED by gen_exports.py from %s -- 不要手改\n'
                '   白名单 = 原厂库 .dynsym 里 st_shndx != 0 的全部条目（%d 个）。\n'
                '   目的：把重建库多出来的模板实例/调试符号收敛成 local，\n'
                '   避免它们在别的进程里抢占同名 UND。 */\n'
                % (os.path.basename(src), len(names)))
        f.write('{\n  global:\n')
        for n in names:
            f.write('    %s;\n' % n)
        f.write('  local: *;\n};\n')
    print('[gen_exports] %d 个导出 -> %s' % (len(names), dst))


if __name__ == '__main__':
    main()
